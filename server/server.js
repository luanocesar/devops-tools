'use strict';
const http = require('http');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawn } = require('child_process');

const BASE = '/devops-tools';
const NAME_RE = /^[A-Za-z0-9_-]{1,64}$/;
const MAX_UPLOAD = 500 * 1024 * 1024;

function createServer(opts = {}) {
  const dataDir = opts.dataDir || path.join(__dirname, '..', 'data');
  const deployScript = opts.deployScript || path.join(__dirname, '..', 'scripts', 'deploy.bat');
  const runDeploy = opts.runDeploy || defaultRunDeploy;
  const projectsDir = path.join(dataDir, 'projects');
  fs.mkdirSync(projectsDir, { recursive: true });

  const projectFile = (n) => path.join(projectsDir, n, 'project.json');
  const loadProject = (n) => {
    if (!NAME_RE.test(n) || !fs.existsSync(projectFile(n))) return null;
    return JSON.parse(fs.readFileSync(projectFile(n), 'utf8'));
  };

  function defaultRunDeploy(project, zipPath) {
    return new Promise((resolve, reject) => {
      const args = ['/c', deployScript, zipPath, project.siteName, project.backendAppPool || '-',
        JSON.stringify(project.apps)];
      const p = spawn('cmd.exe', args, { windowsHide: true });
      let out = '';
      p.stdout.on('data', (d) => (out += d));
      p.stderr.on('data', (d) => (out += d));
      p.on('error', reject);
      p.on('close', (code) => (code === 0 ? resolve(out) : reject(new Error(out || `exit ${code}`))));
    });
  }

  function send(res, status, body, type = 'application/json') {
    res.writeHead(status, { 'Content-Type': type });
    res.end(typeof body === 'string' ? body : JSON.stringify(body));
  }

  function readBody(req, limit) {
    return new Promise((resolve, reject) => {
      const chunks = [];
      let size = 0;
      req.on('data', (c) => {
        size += c.length;
        if (size > limit) { reject(Object.assign(new Error('too large'), { status: 413 })); req.destroy(); return; }
        chunks.push(c);
      });
      req.on('end', () => resolve(Buffer.concat(chunks)));
      req.on('error', reject);
    });
  }

  function clientScript(project, serverUrl) {
    const builds = (project.clientBuildCommands || []).map((c) => `call ${c}\r\nif errorlevel 1 exit /b 1`).join('\r\n');
    return [
      '@echo off',
      'rem Generated by devops-tools. Run from the root of the project in your machine.',
      `set DEVOPS_URL=${serverUrl}${BASE}/api/projects/${project.name}/deploy`,
      `set DEVOPS_TOKEN=${project.token}`,
      `set DEVOPS_PACKAGE=%TEMP%\\${project.name}-package.zip`,
      builds,
      `powershell -NoProfile -Command "if (Test-Path '${project.clientOutputPath}') { if (Test-Path $env:DEVOPS_PACKAGE) { Remove-Item $env:DEVOPS_PACKAGE }; Compress-Archive -Path '${project.clientOutputPath}\\*' -DestinationPath $env:DEVOPS_PACKAGE } else { exit 1 }"`,
      'if errorlevel 1 (echo Could not package output & exit /b 1)',
      'curl.exe --fail -X POST -H "X-Devops-Token: %DEVOPS_TOKEN%" --data-binary "@%DEVOPS_PACKAGE%" "%DEVOPS_URL%"',
      'if errorlevel 1 (echo Deploy failed & exit /b 1)',
      'echo Deploy finished.',
      ''
    ].join('\r\n');
  }

  async function handle(req, res) {
    const url = new URL(req.url, 'http://localhost');
    const host = req.headers.host || 'localhost';
    const serverUrl = `${opts.protocol || 'http'}://${host}`;
    let m;

    if (req.method === 'POST' && url.pathname === `${BASE}/api/projects`) {
      const body = JSON.parse((await readBody(req, 1024 * 1024)).toString() || '{}');
      if (!NAME_RE.test(body.name || '')) return send(res, 400, { error: 'invalid project name' });
      if (!body.siteName || !Array.isArray(body.apps) || !body.apps.length) {
        return send(res, 400, { error: 'siteName and apps are required' });
      }
      if (fs.existsSync(projectFile(body.name))) return send(res, 409, { error: 'project exists' });
      const project = {
        name: body.name,
        siteName: String(body.siteName),
        backendAppPool: body.backendAppPool ? String(body.backendAppPool) : '',
        clientBuildCommands: (body.clientBuildCommands || []).map(String),
        clientOutputPath: String(body.clientOutputPath || 'publish'),
        apps: body.apps.map((a) => ({ name: String(a.name), targetPath: String(a.targetPath), type: String(a.type || 'static') })),
        token: crypto.randomBytes(24).toString('hex')
      };
      fs.mkdirSync(path.join(projectsDir, project.name), { recursive: true });
      fs.writeFileSync(projectFile(project.name), JSON.stringify(project, null, 2));
      return send(res, 201, { name: project.name, path: `${BASE}/${project.name}`,
        installUrl: `${serverUrl}${BASE}/install-client?project=${project.name}&token=${project.token}` });
    }

    if (req.method === 'GET' && url.pathname === `${BASE}/install-client`) {
      const project = loadProject(url.searchParams.get('project') || '');
      if (!project || !safeEqual(url.searchParams.get('token'), project.token)) return send(res, 404, { error: 'not found' });
      res.writeHead(200, { 'Content-Type': 'application/octet-stream',
        'Content-Disposition': `attachment; filename="deploy-${project.name}.bat"` });
      return res.end(clientScript(project, serverUrl));
    }

    if (req.method === 'POST' && (m = url.pathname.match(new RegExp(`^${BASE}/api/projects/([^/]+)/deploy$`)))) {
      const project = loadProject(m[1]);
      if (!project || !safeEqual(req.headers['x-devops-token'], project.token)) return send(res, 401, { error: 'unauthorized' });
      const zip = await readBody(req, MAX_UPLOAD);
      if (!zip.length) return send(res, 400, { error: 'empty package' });
      const zipPath = path.join(projectsDir, project.name, `upload-${Date.now()}.zip`);
      fs.writeFileSync(zipPath, zip);
      try {
        const log = await runDeploy(project, zipPath);
        return send(res, 200, { status: 'deployed', log });
      } catch (e) {
        return send(res, 500, { status: 'failed', error: e.message });
      } finally {
        fs.rmSync(zipPath, { force: true });
      }
    }

    send(res, 404, { error: 'not found' });
  }

  return http.createServer((req, res) => {
    handle(req, res).catch((e) => send(res, e.status || 400, { error: e.message }));
  });
}

function safeEqual(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string') return false;
  const x = Buffer.from(a), y = Buffer.from(b);
  return x.length === y.length && crypto.timingSafeEqual(x, y);
}

if (require.main === module) {
  const port = process.env.PORT || 3000;
  createServer().listen(port, () => console.log(`devops-tools listening on ${port}`));
}

module.exports = { createServer };
